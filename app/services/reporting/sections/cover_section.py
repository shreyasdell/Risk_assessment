"""
Cover Page Section

Generates the cover page with title, metadata, and branding.
"""

from datetime import datetime
from typing import List
from reportlab.platypus import Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.lib.enums import TA_CENTER
from .base_section import BaseSection


class CoverSection(BaseSection):
    """Cover page section."""
    
    def generate(self, data: dict) -> List:
        """Generate cover page content."""
        story = []
        
        application = data.get('application')
        sbom_id = data.get('sbom_id')
        risk_score = data.get('risk_score', 'N/A')
        
        # Add spacing
        story.append(Spacer(1, 2*inch))
        
        # Title
        story.append(Paragraph("Vulnerability Assessment Report", self.styles['ReportTitle']))
        story.append(Spacer(1, 0.5*inch))
        
        # Metadata table
        metadata_data = [
            ['Metric', 'Value'],
            ['Application', application.name if application else 'All Applications'],
            ['Report Date', datetime.now().strftime('%Y-%m-%d')],
            ['SBOM ID', sbom_id or 'N/A'],
            ['Generated By', 'Vulnerability Risk Assessment Tool'],
            ['Risk Rating', str(risk_score)],
        ]
        
        metadata_table = Table(metadata_data, colWidths=[2*inch, 3*inch])
        metadata_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), self.colors['header_bg']),
            ('TEXTCOLOR', (0, 0), (-1, 0), self.colors['header_text']),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 11),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 10),
            ('BACKGROUND', (0, 1), (-1, -1), colors.white),
            ('GRID', (0, 0), (-1, -1), 1, self.colors['border']),
            ('FONTSIZE', (0, 1), (-1, -1), 10),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, self.colors['light_gray']]),
        ]))
        
        story.append(metadata_table)
        
        # Add more spacing
        story.append(Spacer(1, 2*inch))
        
        # Footer
        story.append(Paragraph(
            "Confidential - For Internal Use Only",
            self.styles['BodyText']
        ))
        
        return story
